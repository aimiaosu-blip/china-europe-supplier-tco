"""Rebuild numerical outputs and interpretation without external services."""
from pathlib import Path
import json
import plotly.express as px
from .data import load
from .model import Scenario, tco, rank, sensitivity
from .simulation import simulate, pairwise_probabilities, group_comparison
from .config import CONFIG


def main():
    root = Path(__file__).resolve().parents[1]
    out = root/'results'
    out.mkdir(exist_ok=True)
    df, s = load(), Scenario()
    base = tco(df, s)
    base.to_csv(out/'baseline_tco.csv', index=False)
    sensitivity(df, s).to_csv(out/'sensitivity.csv', index=False)
    summaries, samples = simulate(df, s)
    summaries.to_csv(out/'monte_carlo_summary.csv', index=False)
    pairwise_probabilities(samples).to_csv(out/'pairwise_probabilities.csv',index=False)
    price_ranks = df[['supplier_id','purchase_eur']].copy()
    price_ranks['purchase_rank'] = price_ranks.purchase_eur.rank(method='min')
    price_ranks = price_ranks.merge(base[['supplier_id','tco_eur']],on='supplier_id')
    price_ranks['tco_rank'] = price_ranks.tco_eur.rank(method='min')
    price_ranks['rank_change'] = price_ranks.purchase_rank-price_ranks.tco_rank
    price_ranks.to_csv(out/'purchase_vs_tco_ranks.csv',index=False)
    choices = []
    group_results = []
    for name, w in CONFIG['priorities'].items():
        r = rank(df, s, w)
        r.to_csv(out/f'ranking_{name.lower()}.csv', index=False)
        _, priority_samples = simulate(df,s,cost_weight=w)
        group_results.append({'priority':name,**group_comparison(priority_samples)})
        choices.append(f'| {name} | {w:.0%} | {r.iloc[0].supplier_id} | {r.iloc[0].score:.2f} |')
    import pandas as pd
    pd.DataFrame(group_results).to_csv(out/'group_probabilities.csv',index=False)
    pillar_stresses = []
    for pillar in CONFIG['risk_pillars']:
        risk_weights = {key:float(key==pillar) for key in CONFIG['risk_pillars']}
        focused = rank(df,s,cost_weight=.2,risk_weights=risk_weights)
        pillar_stresses.append({'sole_risk_pillar':pillar,'cost_weight':.2,'preferred_supplier':focused.iloc[0].supplier_id})
    pd.DataFrame(pillar_stresses).to_csv(out/'single_pillar_stresses.csv',index=False)
    chart = px.scatter(rank(df), x='tco_eur', y='residual_risk', color='region', text='supplier_id',
                       title='Synthetic supplier trade-offs — no empirical country inference')
    chart.write_html(out/'supplier_comparison.html', include_plotlyjs=True)
    cheapest = df.loc[df.purchase_eur.idxmin(), 'supplier_id']
    lifecycle = base.loc[base.tco_eur.idxmin(), 'supplier_id']
    leader_statement = ('The price and lifecycle leaders coincide in this sample.' if cheapest == lifecycle else 'The lifecycle model changes the preferred supplier compared with purchase price alone in this sample.')
    text = f'''# Results interpretation — synthetic simulation only

Generated by `python -m supplier_tco.report`. Dataset seed 42; simulation seed 2026; 5,000 joint draws.
Base case: 15 years, 6% real discount rate, EUR 0.15/kWh, 2% real maintenance escalation and EUR 2,500/hour lost contribution margin. Reference CNY/EUR is 7.8 (an assumption, not a live rate).

Lowest purchase price: **{cheapest}**. Lowest expected lifecycle TCO: **{lifecycle}**.
{leader_statement} This is not an estimated country effect. See `purchase_vs_tco_ranks.csv` for all rank changes.

| Purchasing priority | TCO weight | Preferred supplier | MCDA score |
|---|---:|---|---:|
''' + '\n'.join(choices) + '''

The winner happens to remain the same across the three default cost/risk mixes; no winner switch is asserted. `single_pillar_stresses.csv` isolates each pillar at 80% total utility and TCO at 20% to show preference sensitivity. These extreme diagnostic weightings are not recommended policy. Rankings depend on assumed risk weights, utility anchors and cost inputs. A supplier preferred under one purchasing priority need not remain preferred under another. Inspect the full ranking CSVs rather than interpreting region labels as causal variables.

## Uncertainty and decisions
`monte_carlo_summary.csv` separates distribution percentiles from Monte Carlo mean confidence intervals. Probability-best represents relative preference within this 12-supplier shortlist and the assumed uncertainty model. CVaR95 is the average worst-tail cost, not a fee to add to TCO. A risk-averse decision maker can substitute CVaR95 for mean cost.

## Paired and regional-shortlist comparisons
`pairwise_probabilities.csv` reports P(A scores higher than B) and ties separately using paired joint draws. `group_probabilities.csv` reports the probability that the average eligible China-labelled supplier score exceeds the average eligible Europe-labelled score for each priority. This is a finite synthetic shortlist comparison, not a population or country effect.

## Sensitivity
`sensitivity.csv` varies energy prices, maintenance/parts level and real escalation, exposed-spend FX, CNY/EUR, common equipment lifetime and discount rate. All else equal, energy/maintenance/FX increases cannot reduce cost; higher discount rates reduce positive future cost PV. Lifetime comparisons also report equivalent annual cost to reflect unequal service horizons. These are one-at-a-time analyses, not estimated elasticities from observed market data.

## Research interpretation
H1 is illustrated if purchase-price and lifecycle-cost leaders differ. H2 is illustrated if priority scenarios change the winner. H3 is explored through uncertainty intervals and probability-best rather than a formal significance test. No hypothesis about real Chinese-versus-European supplier superiority is tested or supported here.

## Before a real sourcing recommendation
Obtain comparable RFQs, acceptance-test evidence, verified regulatory documentation, service SLAs, plant energy and failure records, and logistics/FX terms. Re-estimate uncertainty and criterion overlap with engineering, finance and procurement stakeholders. Validate mandatory gates before applying compensatory scoring.
'''
    (root/'docs/results_interpretation.md').write_text(text)
    (out/'run_manifest.json').write_text(json.dumps({'dataset_seed':42,'simulation_seed':2026,'draws':5000,
        'scenario':s.__dict__, 'configuration':CONFIG, 'data':'100% synthetic', 'cost_anchor_eur':[2000000,8000000]}, indent=2))
    print(text[:1200])

if __name__ == '__main__':
    main()
